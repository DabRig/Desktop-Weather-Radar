<#
.SYNOPSIS
  Developer tool: does the skin's one-time location setup from PowerShell.

.DESCRIPTION
  Users don't need this: the skin sets itself up on first load and after location
  changes (see "location setup" in Radar.lua). This script does the same work for
  tests and for checking the skin's results. It:
    1. validates the settings,
    2. computes a square Web Mercator (EPSG:3857) box centred on the location,
    3. asks NOAA which radar mosaic (CONUS, CARIB, ...) covers the point,
    4. asks api.weather.gov for the nearest NWS radar station and observation stations,
    5. downloads the four public-domain US Census TIGER map layers into DownloadFile\,
    6. writes @Resources\Location.inc.
  It needs no admin rights and changes nothing outside the skin folder.

.PARAMETER SkinDir
  The DesktopRadar skin folder. Defaults to the project copy next to this script.
#>
[CmdletBinding()]
param([string]$SkinDir)

$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName System.Drawing
[Net.ServicePointManager]::SecurityProtocol = [Net.SecurityProtocolType]::Tls12

. (Join-Path $PSScriptRoot 'RadarCommon.ps1')

if (-not $SkinDir) { $SkinDir = Join-Path $PSScriptRoot '..\skin\DesktopRadar' }
$SkinDir = (Resolve-Path $SkinDir).Path
$res = Join-Path $SkinDir '@Resources'
$img = Join-Path $res 'Images'
New-Item -ItemType Directory -Force $img | Out-Null

$s = Read-RadarSettings (Join-Path $res 'Settings.inc')
Write-Host "Location: $($s.LocationName) ($($s.Latitude), $($s.Longitude)), radius $($s.RadiusKm) km, $($s.Size)px"

$bbox = Get-MercatorBBox -Latitude $s.Lat -Longitude $s.Lon -RadiusKm $s.Radius
$bboxText = ($bbox | ForEach-Object { [math]::Round($_, 1).ToString([Globalization.CultureInfo]::InvariantCulture) }) -join ','
Write-Host "BBox (EPSG:3857): $bboxText"

# Which NOAA mosaic covers the point?
$region = Get-RadarRegion -Latitude $s.Lat -Longitude $s.Lon
Write-Host "Radar mosaic: $region"

# Nearest NWS radar station, for the click-through link. Optional.
$station = ''; $obsStations = ''
$pt = '{0},{1}' -f $s.Lat.ToString('0.####', [Globalization.CultureInfo]::InvariantCulture), $s.Lon.ToString('0.####', [Globalization.CultureInfo]::InvariantCulture)
try {
  $p = Invoke-RestMethod -UseBasicParsing -TimeoutSec 30 -UserAgent $RadarUserAgent -Uri "https://api.weather.gov/points/$pt"
  $station = [string]$p.properties.radarStation
  # Nearest surface observation stations, closest first. The skin falls back down this
  # list when a station's latest report has no wind (NWS marks missing values as null).
  $os = Invoke-RestMethod -UseBasicParsing -TimeoutSec 30 -UserAgent $RadarUserAgent -Uri ([string]$p.properties.observationStations + '?limit=3')
  $obsStations = (@($os.features | ForEach-Object { $_.properties.stationIdentifier }) | Select-Object -First 3) -join ','
} catch { Write-Warning "Could not look up NWS stations: $($_.Exception.Message)" }
Write-Host "Surface wind stations: $(if ($obsStations) { $obsStations } else { '(none; wind display off)' })"
if ($station) { $nwsUrl = "https://radar.weather.gov/station/$station/standard" } else { $nwsUrl = 'https://radar.weather.gov/' }
Write-Host "NWS radar link: $nwsUrl"

# Basemap: public-domain US Census TIGERweb layers, the same four files the skin downloads
# itself during setup. Rainmeter recolours them (ColorMatrix in Radar.ini).
$tiger = 'https://tigerweb.geo.census.gov/arcgis/rest/services/TIGERweb'
$layers = @(
  @{ Name = 'land';     Url = "$tiger/USLandmass/MapServer";       Show = '0' },
  @{ Name = 'water';    Url = "$tiger/Hydro/MapServer";            Show = '1' },
  @{ Name = 'counties'; Url = "$tiger/tigerWMS_Current/MapServer"; Show = '82' },
  @{ Name = 'roads';    Url = "$tiger/Transportation/MapServer";   Show = '0,1,2' }
)
$dl = Join-Path $SkinDir 'DownloadFile'
New-Item -ItemType Directory -Force $dl | Out-Null
$n = $s.Size
foreach ($L in $layers) {
  $file = Join-Path $dl "layer_$($L.Name).png"
  $q = @{ bbox = $bboxText; bboxSR = '3857'; imageSR = '3857'; size = "$n,$n"; format = 'png32'; transparent = 'true'; layers = "show:$($L.Show)"; f = 'image' }
  if (-not (Save-ArcGisImage -Url "$($L.Url)/export" -Query $q -OutFile $file)) { Write-Warning "Map layer '$($L.Name)' unavailable." }
}
Write-Host "Map layers: $dl\layer_*.png"

# 1x1 transparent PNG used by the skin at load time instead of a network request.
$blank = Join-Path $img 'blank.png'
if (-not (Test-Path $blank)) {
  $b = New-Object Drawing.Bitmap 1, 1, ([Drawing.Imaging.PixelFormat]::Format32bppArgb)
  $b.SetPixel(0, 0, [Drawing.Color]::FromArgb(0, 0, 0, 0)); $b.Save($blank, [Drawing.Imaging.ImageFormat]::Png); $b.Dispose()
}

$generatedFor = '{0},{1},{2},{3}' -f $s.Latitude, $s.Longitude, $s.RadiusKm, $s.SizeText
$loc = @(
  "; Generated by tools\Update-Location.ps1 on $((Get-Date).ToString('yyyy-MM-dd HH:mm')). Do not edit by hand:",
  '; change Settings.inc and run the script again.',
  '[Variables]',
  "GeneratedFor=$generatedFor",
  "BBox=$bboxText",
  "Region=$region",
  "RadarStation=$station",
  "NWSRadarURL=$nwsUrl",
  "ObsStations=$obsStations",
  "WindStation=$(($obsStations -split ',')[0])",
  "AlertPoint=$pt",
  "ForecastURL=https://forecast.weather.gov/MapClick.php?lat=$($pt.Split(',')[0])&lon=$($pt.Split(',')[1])"
)
Write-AsciiFile (Join-Path $res 'Location.inc') $loc

$state = Join-Path $res 'State.inc'
if (-not (Test-Path $state)) {
  Write-AsciiFile $state @('; Written by the skin at runtime. Safe to delete; the skin downloads a fresh frame.', '[Variables]', 'Slot=a', 'ObsEpochMs=0', 'LastSuccess=0')
}
Write-Host 'Done. Refresh the skin in Rainmeter to apply.'
